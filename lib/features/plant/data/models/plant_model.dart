import 'package:plenty/features/plant/domain/entities/plant_entity.dart';

/// Data Transfer Object (DTO) for Plant JSON & local serialization.
class PlantModel extends PlantEntity {
  const PlantModel({
    required super.id,
    required super.name,
    required super.scientificName,
    required super.location,
    required super.containerDetail,
    required super.lightIntensity,
    required super.distanceFromWindow,
    required super.specificArea,
    required super.imageAsset,
    required super.careLevel,
    required super.waterSchedule,
    required super.lightSchedule,
    required super.toxicity,
    required super.description,
    required super.maxHeight,
    required super.growthRate,
    required super.growthCycle,
    required super.pruningSeason,
    required super.flowerStatus,
    required super.pests,
    super.isCustom = false,
    super.timeCapsuleMessage = '',
    super.hasTimeCapsule = false,
    required super.nextWaterDate,
    required super.lastCleanedDate,
  });

  factory PlantModel.fromEntity(PlantEntity entity) {
    return PlantModel(
      id: entity.id,
      name: entity.name,
      scientificName: entity.scientificName,
      location: entity.location,
      containerDetail: entity.containerDetail,
      lightIntensity: entity.lightIntensity,
      distanceFromWindow: entity.distanceFromWindow,
      specificArea: entity.specificArea,
      imageAsset: entity.imageAsset,
      careLevel: entity.careLevel,
      waterSchedule: entity.waterSchedule,
      lightSchedule: entity.lightSchedule,
      toxicity: entity.toxicity,
      description: entity.description,
      maxHeight: entity.maxHeight,
      growthRate: entity.growthRate,
      growthCycle: entity.growthCycle,
      pruningSeason: entity.pruningSeason,
      flowerStatus: entity.flowerStatus,
      pests: entity.pests,
      isCustom: entity.isCustom,
      timeCapsuleMessage: entity.timeCapsuleMessage,
      hasTimeCapsule: entity.hasTimeCapsule,
      nextWaterDate: entity.nextWaterDate,
      lastCleanedDate: entity.lastCleanedDate,
    );
  }

  factory PlantModel.fromJson(Map<String, dynamic> json) {
    return PlantModel(
      id: (json['id'] as String?) ?? '',
      name: (json['name'] as String?) ?? '',
      scientificName: (json['scientificName'] as String?) ?? '',
      location: (json['location'] as String?) ?? '',
      containerDetail: (json['containerDetail'] as String?) ?? '',
      lightIntensity: (json['lightIntensity'] as String?) ?? '',
      distanceFromWindow: (json['distanceFromWindow'] as String?) ?? '',
      specificArea: (json['specificArea'] as String?) ?? '',
      imageAsset: (json['imageAsset'] as String?) ?? '',
      careLevel: (json['careLevel'] as String?) ?? '',
      waterSchedule: (json['waterSchedule'] as String?) ?? '',
      lightSchedule: (json['lightSchedule'] as String?) ?? '',
      toxicity: (json['toxicity'] as String?) ?? '',
      description: (json['description'] as String?) ?? '',
      maxHeight: (json['maxHeight'] as String?) ?? '',
      growthRate: (json['growthRate'] as String?) ?? '',
      growthCycle: (json['growthCycle'] as String?) ?? '',
      pruningSeason: (json['pruningSeason'] as String?) ?? '',
      flowerStatus: (json['flowerStatus'] as String?) ?? '',
      pests: (json['pests'] as String?) ?? '',
      isCustom: (json['isCustom'] as bool?) ?? false,
      timeCapsuleMessage: (json['timeCapsuleMessage'] as String?) ?? '',
      hasTimeCapsule: (json['hasTimeCapsule'] as bool?) ?? false,
      nextWaterDate: (json['nextWaterDate'] as String?) ?? '',
      lastCleanedDate: (json['lastCleanedDate'] as String?) ?? '',
    );
  }

  Map<String, dynamic> toJson() {
    return <String, dynamic>{
      'id': id,
      'name': name,
      'scientificName': scientificName,
      'location': location,
      'containerDetail': containerDetail,
      'lightIntensity': lightIntensity,
      'distanceFromWindow': distanceFromWindow,
      'specificArea': specificArea,
      'imageAsset': imageAsset,
      'careLevel': careLevel,
      'waterSchedule': waterSchedule,
      'lightSchedule': lightSchedule,
      'toxicity': toxicity,
      'description': description,
      'maxHeight': maxHeight,
      'growthRate': growthRate,
      'growthCycle': growthCycle,
      'pruningSeason': pruningSeason,
      'flowerStatus': flowerStatus,
      'pests': pests,
      'isCustom': isCustom,
      'timeCapsuleMessage': timeCapsuleMessage,
      'hasTimeCapsule': hasTimeCapsule,
      'nextWaterDate': nextWaterDate,
      'lastCleanedDate': lastCleanedDate,
    };
  }

  PlantEntity toEntity() {
    return PlantEntity(
      id: id,
      name: name,
      scientificName: scientificName,
      location: location,
      containerDetail: containerDetail,
      lightIntensity: lightIntensity,
      distanceFromWindow: distanceFromWindow,
      specificArea: specificArea,
      imageAsset: imageAsset,
      careLevel: careLevel,
      waterSchedule: waterSchedule,
      lightSchedule: lightSchedule,
      toxicity: toxicity,
      description: description,
      maxHeight: maxHeight,
      growthRate: growthRate,
      growthCycle: growthCycle,
      pruningSeason: pruningSeason,
      flowerStatus: flowerStatus,
      pests: pests,
      isCustom: isCustom,
      timeCapsuleMessage: timeCapsuleMessage,
      hasTimeCapsule: hasTimeCapsule,
      nextWaterDate: nextWaterDate,
      lastCleanedDate: lastCleanedDate,
    );
  }
}
